import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const files=['src/lib/import-pipeline/folder-watch-service.ts','src/lib/import-pipeline/folder-watch-store.ts','src/lib/import-pipeline/canonical-text-orchestrator.ts','src/lib/import-pipeline/incremental-import-ledger.ts','supabase/migrations/20260825110001_watched_report_folders.sql','supabase/migrations/20260904002000_close_watched_report_file_direct_dml_boundary.sql'];
for(const file of files)if(!fs.existsSync(path.join(root,file)))throw new Error(`Missing watched-report pipeline file: ${file}`);
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const watcher=read(files[0]);
for(const token of ['SHA-256','scanWatchedDirectory','startWatchedFolder','failedFiles'])if(!watcher.includes(token))throw new Error(`Watcher contract missing: ${token}`);
const text=read(files[2]);
for(const token of ['normalizeExtractedText','canonical_text','structured_source_fallback','continueWithFallback','CANONICAL_TEXT_UNAVAILABLE_ANALYSIS_CONTINUES'])if(!text.includes(token))throw new Error(`Text-first fallback contract missing: ${token}`);
const incremental=read(files[3]);
for(const token of ['process_changed','skip_unchanged','deletedRows','reconcileRows'])if(!incremental.includes(token))throw new Error(`Incremental reconciliation contract missing: ${token}`);
const sql=read(files[4]);
for(const token of ['watched_report_folders','watched_report_files','canonical_text_provenance','WITH CHECK','record_watched_report_file'])if(!sql.includes(token))throw new Error(`Persistence contract missing: ${token}`);
const dmlBoundary=read(files[5]);
const revoke='REVOKE INSERT, UPDATE, DELETE ON TABLE public.watched_report_files FROM authenticated';
const recorder='GRANT EXECUTE ON FUNCTION public.record_watched_report_file';
if(!dmlBoundary.includes(revoke)||!dmlBoundary.includes(recorder))throw new Error('Watched direct-DML boundary is incomplete');
const validateDmlBoundary=(candidate)=>{
  if(!candidate.includes(revoke))throw new Error('Watched direct-DML revoke missing');
  if(!candidate.includes(recorder))throw new Error('Watched recorder RPC grant missing');
};
validateDmlBoundary(dmlBoundary);
const weakened=dmlBoundary.replace(revoke,'GRANT INSERT, UPDATE, DELETE ON TABLE public.watched_report_files FROM authenticated');
assert.throws(()=>validateDmlBoundary(weakened),/direct-DML revoke missing/);
const roadmapPath='docs/IMPLEMENTATION_ROADMAP.md';
if(!fs.existsSync(path.join(root,roadmapPath)))throw new Error(`Missing master requirements file: ${roadmapPath}`);
const roadmap=read(roadmapPath);
for(const token of ['Automatic watched-folder synchronization','Revised reports are fingerprinted','First-stage text-first extraction/reconstruction','Extraction is a quality layer, not a single point of failure','Canonical report reconstruction must preserve','parse-once cache and report-version lineage'])if(!roadmap.includes(token))throw new Error(`Master requirement missing: ${token}`);
console.log('Watched reports + text-first fallback + canonical direct-write boundary + master-plan contract: PASS');
